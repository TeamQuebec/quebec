#!/usr/bin/env node
/**
 * Quebec — synthetic dataset generator.
 *
 * Produces `lib/mockData/users.ts`: a set of fully fabricated identity records
 * used to power the demo. No real personal data is used, collected or stored.
 *
 * Run:  npm run generate:users
 *
 * Deterministic (seeded PRNG) so re-running reproduces the same dataset.
 * The two demo-anchor records (QBC-8X92-1F over-18, QBC-7KD4-M3 under-18)
 * are pinned so copy, example chips and the curated seed stay valid.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "..", "lib", "mockData", "users.ts");

// ---- mulberry32: deterministic PRNG ---------------------------------------
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(20260830);

// ---- Synthetic name pools (invented combinations, not real people) --------
const FIRST = [
  "Adaeze", "Chinedu", "Amina", "Oluwaseun", "Ngozi", "Ibrahim", "Tobi",
  "Funke", "Emeka", "Zainab", "Ifeanyi", "Yemi", "Chiamaka", "Abubakar",
  "Simi", "Kelechi", "Halima", "Bayo", "Nneka", "Tunde", "Fatima", "Musa",
];
const LAST = [
  "Okafor", "Nwachukwu", "Bello", "Adeyemi", "Eze", "Musa", "Akinloye",
  "Adebayo", "Obi", "Abdullahi", "Uche", "Alabi", "Nwosu", "Sani", "Ogunleye",
  "Umeh", "Danjuma", "Lawal", "Okeke", "Balogun", "Yusuf", "Adeleke",
];

const REF_CHARS = "ABCDEFGHJKLMNPQRSTUVWXYZ123456789";

function ref() {
  let out = "QBC-";
  for (let i = 0; i < 4; i++) out += REF_CHARS[Math.floor(rand() * REF_CHARS.length)];
  out += "-";
  for (let i = 0; i < 2; i++) out += REF_CHARS[Math.floor(rand() * REF_CHARS.length)];
  return out;
}

function nin() {
  let out = "";
  for (let i = 0; i < 11; i++) out += Math.floor(rand() * 10);
  return out;
}

/** Random ISO date between 1985 and 2013 (a real mix of under/over 18). */
function dob() {
  const year = 1985 + Math.floor(rand() * 29); // 1985..2013
  const month = 1 + Math.floor(rand() * 12);
  const day = 1 + Math.floor(rand() * 28);
  const iso = `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  return { iso, age: new Date().getFullYear() - year };
}

// ---- Assemble records ------------------------------------------------------
const records = [];
const usedNames = new Set();
const usedRefs = new Set();

function pickName() {
  let name = "";
  do {
    name = `${FIRST[Math.floor(rand() * FIRST.length)]} ${LAST[Math.floor(rand() * LAST.length)]}`;
  } while (usedNames.has(name));
  usedNames.add(name);
  return name;
}

// 16 records total; guarantee several under-18 entries.
while (records.length < 16) {
  const d = dob();
  const under18 = records.length % 4 === 1; // every 4th is a teenager
  const record = {
    uniqueId: ref(),
    name: pickName(),
    dob: under18 ? `${2009 + Math.floor(rand() * 4)}-${String(1 + Math.floor(rand() * 12)).padStart(2, "0")}-${String(1 + Math.floor(rand() * 28)).padStart(2, "0")}` : d.iso,
    nin: nin(),
    kycStatus: under18 ? "self_asserted" : rand() > 0.35 ? "verified" : "self_asserted",
  };
  if (usedRefs.has(record.uniqueId)) continue;
  usedRefs.add(record.uniqueId);
  // Deterministic id derived from the (unique) reference, so re-runs match.
  record.id = `id_${record.uniqueId.toLowerCase().replace(/-/g, "").slice(0, 6)}`;
  records.push(record);
}

// Pin the two demo anchors so copy + examples stay valid.
const OVER = records.find((r) => new Date(r.dob).getFullYear() <= 1998);
if (OVER) {
  OVER.id = "id_adaeze";
  OVER.uniqueId = "QBC-8X92-1F";
  OVER.name = "Adaeze Okafor";
  OVER.dob = "1994-03-12";
  OVER.nin = "40172345678";
  OVER.kycStatus = "verified";
}
const UNDER = records.find((r) => new Date(r.dob).getFullYear() >= 2008);
if (UNDER) {
  UNDER.id = "id_ibrahim";
  UNDER.uniqueId = "QBC-7KD4-M3";
  UNDER.name = "Ibrahim Musa";
  UNDER.dob = "2009-12-07";
  UNDER.nin = "46329087154";
  UNDER.kycStatus = "self_asserted";
}

// ---- Write the module ------------------------------------------------------
const lines = records
  .map(
    (r) =>
      `  { id: "${r.id}", uniqueId: "${r.uniqueId}", name: "${r.name}", dob: "${r.dob}", nin: "${r.nin}", kycStatus: "${r.kycStatus}" },`
  )
  .join("\n");

const content = `import type { KycStatus } from "@/lib/types";
import { daysAgo } from "@/lib/format";

/**
 * SYNTHETIC IDENTITY DATASET  (generated by \`npm run generate:users\`)
 * -------------------------------------------------------------------
 * Every record is fabricated for demonstration: invented Nigerian-style
 * names, random dates of birth, and 11-digit NIN-format numbers that
 * resemble no real registry entry. No real personal information is used,
 * collected or stored at any stage of this project.
 *
 * Regenerate with:  npm run generate:users
 */

export interface SyntheticUserRecord {
  id: string;
  uniqueId: string;
  name: string;
  dob: string; // ISO yyyy-mm-dd
  nin: string; // 11 digits, fake
  kycStatus: KycStatus;
}

/** Reference used in copy / demos — the curated, document-verified identity. */
export const DEMO_IDENTITY_REFERENCE = "QBC-8X92-1F";
/** Reference used to demo a NO on "Is over 18?". */
export const DEMO_UNDER18_REFERENCE = "QBC-7KD4-M3";
/** Deliberately not present in the dataset, for the NO MATCH outcome. */
export const DEMO_NOT_FOUND_REFERENCE = "QBC-9ZZZ-00";

export const SYNTHETIC_USERS: SyntheticUserRecord[] = [
${lines}
];

/** Built from SYNTHETIC_USERS at runtime so createdAt stays "recent" for demos. */
export interface SeedIdentity extends SyntheticUserRecord {
  createdAt: string;
}

export function buildSeedIdentities(): SeedIdentity[] {
  return SYNTHETIC_USERS.map((u, i) => ({
    ...u,
    createdAt: daysAgo(9 - (i % 7)),
  }));
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, content, "utf8");
console.log(`Wrote ${records.length} synthetic records -> ${OUT}`);
